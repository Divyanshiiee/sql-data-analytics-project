SELECT 'Customer who placed an order', COUNT(DISTINCT customer_key) FROM gold.fact_sales

--Magnitude Analysis: Compare the measure values by categories. It helps us understand the importance of different categories.
--1.Find total customers by country
SELECT
country,
COUNT(customer_id) AS total_customer
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customer DESC

--2.Find total customers by gender
SELECT
gender,
COUNT(customer_id) AS total_customer
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customer DESC

--3.Find total product by category
SELECT
category,
COUNT(product_id) AS no_of_product
FROM gold.dim_products
GROUP BY category
ORDER BY no_of_product DESC

--total product by sub category
SELECT 
subcategory,
COUNT(product_id) AS no_of_product
FROM gold.dim_products
GROUP BY subcategory
ORDER BY no_of_product DESC

--4.What is the average cost in each category?
SELECT
category,
AVG(cost) AS avg_cost
FROM gold.dim_products
GROUP BY category
ORDER BY avg_cost DESC

--5.What is the total revenue generated for each category?
SELECT
p.category,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key=f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC

--6.Find total revenue generated by each customer
SELECT
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key=f.customer_key
GROUP BY c.customer_key,
         c.first_name,
         c.last_name
ORDER BY total_revenue DESC

--7.What is the distribution of sold item across each country?
SELECT
c.country,
SUM(f.quantity) AS item_sold
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key=f.customer_key
GROUP BY c.country
ORDER BY item_sold DESC



--Ranking Analysis

--Which 5 products generate the highest revenue
SELECT TOP 5
p.product_name,
SUM(f.sales_amount) AS revenue
FROM gold.dim_products p
LEFT JOIN gold.fact_sales f
ON p.product_key=f.product_key
GROUP BY p.product_name
ORDER BY revenue DESC

--What are the 5 worst-performing products in terms of sales
SELECT TOP 5
p.product_name,
SUM(f.sales_amount) AS revenue
FROM gold.dim_products p
LEFT JOIN gold.fact_sales f
ON p.product_key=f.product_key
GROUP BY p.product_name
HAVING SUM(f.sales_amount) IS NOT NULL
ORDER BY revenue ASC

--Top 10 customer who have generated the highest revenue
SELECT TOP 10
    c.customer_id,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
    FROM gold.fact_sales f
    LEFT JOIN gold.dim_customers c
    ON c.customer_id=f.customer_key
    GROUP BY customer_id,
             c.first_name,
             c.last_name
    HAVING SUM(f.sales_amount) IS NOT NULL
    ORDER BY total_revenue DESC

--Top 3 customers with the fewest orders
SELECT TOP 3
    c.customer_id,
    c.first_name,
    c.last_name,
    COUNT(f.order_number) AS no_of_orders
    FROM gold.fact_sales f
    LEFT JOIN gold.dim_customers c
    ON c.customer_id=f.customer_key
    GROUP BY customer_id,
             c.first_name,
             c.last_name
    HAVING SUM(f.sales_amount) IS NOT NULL
    ORDER BY no_of_orders ASC
