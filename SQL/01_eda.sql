--Date Exploration
--Identify the earliest and latest dates, understand the scope of data and the timespan.
--Find the Date of the First and the Last orders
--Find how many years of sales are available
SELECT
MIN(order_date) AS First_Order,
MAX(order_date) AS Last_Order,
DATEDIFF(MONTH, MIN(order_date),MAX(order_date)) AS order_range_month
FROM gold.fact_sales

--Find youngest and the oldest customer
SELECT
MIN(birthdate) AS youngest_customer,
DATEDIFF(YEAR,MIN(birthdate),GETDATE()) AS oldest_customer_age,
MAX(birthdate) AS oldest_customer,
DATEDIFF(YEAR,MAX(birthdate),GETDATE()) AS youngest_customer_age
FROM gold.dim_customers

--Measures Exploration
--Calculate the Metric of the Business
--Highest Level of Aggregation | Lowest Level of Details-
--1. Find the Total Sales
SELECT SUM(sales_amount) AS total_sales FROM gold.fact_sales;

--2.Find how many items are sold
SELECT SUM(quantity) AS total_quantity FROM gold.fact_sales;

--3.Find the Average Selling Price
SELECT AVG(price) AS average_selling_price FROM gold.fact_sales;

--4.Find the Total Number of Orders
SELECT COUNT(DISTINCT order_number) AS total_number_of_orders FROM gold.fact_sales;

--5.Find the Total Number of Products
SELECT COUNT(DISTINCT product_name)  AS total_number_products FROM gold.dim_products;

--6.Find the Total Number of Customers
SELECT COUNT (customer_id) AS total_customer FROM gold.dim_customers;

--7.Find the Total Number of Customers that has Placed an Order
SELECT COUNT(DISTINCT customer_key) AS total_cust_placed_order FROM gold.fact_sales;

--Generate a Report that shows all key metrics of the business

SELECT 'Total Sales'AS measure_name, SUM(sales_amount) AS measure_value FROM gold.fact_sales
